import type { MenuOp, SelectionKind } from "./operationMenu";

export interface ParamSpec {
  parameterId: string;
  kind: "quantity" | "boolean" | "enum" | "string" | "queryList" | "matrix";
  label: string;
  default: unknown;
  units?: string;
  min?: number;
  max?: number;
  step?: number;
  enumValues?: string[];
  hidden?: boolean; // not shown in the VR param panel, still sent to kernel
}

export interface FeatureMapEntry {
  featureType: string;
  label: string;
  kernelOp: string | null; // executor switch case / worker op, or null (non-geometry)
  builder: string | null; // build*Node helper name, or null
  selectionKinds: SelectionKind[]; // context-menu visibility
  status: "implemented" | "gap" | "deferred";
  params: ParamSpec[];
}

const Q = (
  parameterId: string,
  label: string,
  defaultVal: number,
  units = "m",
  min = 0,
): ParamSpec => ({
  kind: "quantity",
  parameterId,
  label,
  default: defaultVal,
  units,
  min,
});

