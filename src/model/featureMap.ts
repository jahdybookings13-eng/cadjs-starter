export function feature(featureType: string): FeatureMapEntry | undefined {
  return FEATURE_MAP.find((e) => e.featureType === featureType);
}

export function featuresBySelection(kind: SelectionKind): FeatureMapEntry[] {
  return FEATURE_MAP.filter((e) => e.selectionKinds.includes(kind));
}

export function implementedBySelection(kind: SelectionKind): MenuOp[] {
  return featuresBySelection(kind)
    .filter((e) => e.status === "implemented")
    .map(
      (e): MenuOp => ({
        id: e.featureType,
        label: e.label,
        status: "ready" as const,
        featureType: e.kernelOp ?? null,
        ...(e.params.length ? { note: `${e.params.length} param(s)` } : {}),
      }),
    );
}

export function allFeatureTypes(): string[] {
  return FEATURE_MAP.map((e) => e.featureType);
}

export function gapTypes(): string[] {
  return FEATURE_MAP.filter((e) => e.status !== "implemented").map(
    (e) => e.featureType,
  );
}
